export function iconNames(): string[] {
  return Object.keys(ICONS);
}

export function paintIcon(name: string): PixelBuffer {
  const rows = ICONS[name];
  if (!rows) throw new Error(`Unknown icon: ${name}`);
  const maskW = Math.max(...rows.map((r) => r.length));
  const maskH = rows.length;
  const scale = Math.floor(ICON_SIZE / Math.max(maskW, maskH));
  const pw = maskW * scale;
  const ph = maskH * scale;
  const buf = new PixelBuffer(ICON_SIZE, ICON_SIZE);
  const ox = Math.floor((ICON_SIZE - pw) / 2);
  const oy = Math.floor((ICON_SIZE - ph) / 2);
  for (let my = 0; my < maskH; my++) {
    const row = rows[my]!;
    for (let mx = 0; mx < row.length; mx++) {
      const color = ICON_PALETTE[row[mx]!];
      if (color === undefined) continue;
      for (let dy = 0; dy < scale; dy++) {
        for (let dx = 0; dx < scale; dx++) {
          buf.set(ox + mx * scale + dx, oy + my * scale + dy, color);
        }
      }
    }
  }
  return buf;
}
